-- ============================================================================
-- 020_retribution_annual_bills.sql
--
-- Retribusi tahunan (mis. Jaspro) dapat dicicil. Sisa tagihan tahun lalu
-- otomatis tampil sebagai tunggakan pada tahun berikutnya.
--
-- Isi:
--   1) retribution_types: billing_period + allow_installment
--   2) tabel retribution_bills (satu baris = satu kewajiban per lapak/jenis/tahun)
--   3) transactions: bill_id + period_year
--   4) view retribution_bill_balances (dibayar/sisa dihitung dari transaksi)
--   5) fungsi generate_retribution_bills(market, tahun, jenis)
--   6) trigger: transaksi bertagihan tidak boleh melebihi sisa / beda lapak
--   7) RLS
--   8) seed jenis Jaspro tahunan untuk pasar NGD (tanpa tarif)
--
-- Idempoten. Jalankan di Supabase SQL Editor.
-- ============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- 1) Jenis retribusi: periode tagihan + izin cicilan
-- ---------------------------------------------------------------------------
ALTER TABLE public.retribution_types
  ADD COLUMN IF NOT EXISTS billing_period text,
  ADD COLUMN IF NOT EXISTS allow_installment boolean;

UPDATE public.retribution_types
SET billing_period = CASE
  WHEN upper(coalesce(unit, '') || ' ' || coalesce(name, '')) ~ 'TAHUN' THEN 'TAHUNAN'
  WHEN upper(coalesce(unit, '') || ' ' || coalesce(name, '')) ~ 'BULAN' THEN 'BULANAN'
  ELSE 'HARIAN'
END
WHERE billing_period IS NULL;

UPDATE public.retribution_types
SET allow_installment = (billing_period = 'TAHUNAN')
WHERE allow_installment IS NULL;

ALTER TABLE public.retribution_types
  ALTER COLUMN billing_period SET DEFAULT 'HARIAN',
  ALTER COLUMN allow_installment SET DEFAULT false;

ALTER TABLE public.retribution_types
  ALTER COLUMN billing_period SET NOT NULL,
  ALTER COLUMN allow_installment SET NOT NULL;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'retribution_types_billing_period_check'
  ) THEN
    ALTER TABLE public.retribution_types
      ADD CONSTRAINT retribution_types_billing_period_check
      CHECK (billing_period IN ('HARIAN', 'BULANAN', 'TAHUNAN'));
  END IF;
END $$;

-- ---------------------------------------------------------------------------
-- 2) Tagihan tahunan
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.retribution_bills (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  market_id bigint NOT NULL REFERENCES public.markets(id) ON DELETE CASCADE,
  stall_id bigint NOT NULL REFERENCES public.stalls(id) ON DELETE CASCADE,
  types_id bigint NOT NULL REFERENCES public.retribution_types(id) ON DELETE RESTRICT,
  period_year integer NOT NULL CHECK (period_year BETWEEN 2000 AND 2100),
  amount_due numeric(15,2) NOT NULL CHECK (amount_due >= 0),
  due_date date,
  status text NOT NULL DEFAULT 'AKTIF' CHECK (status IN ('AKTIF', 'DIBATALKAN')),
  note text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT retribution_bills_unique UNIQUE (stall_id, types_id, period_year)
);

CREATE INDEX IF NOT EXISTS idx_retribution_bills_market_year
  ON public.retribution_bills (market_id, period_year);
CREATE INDEX IF NOT EXISTS idx_retribution_bills_stall
  ON public.retribution_bills (stall_id);

-- ---------------------------------------------------------------------------
-- 3) Transaksi -> tagihan
-- ---------------------------------------------------------------------------
ALTER TABLE public.transactions
  ADD COLUMN IF NOT EXISTS bill_id bigint REFERENCES public.retribution_bills(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS period_year integer;

CREATE INDEX IF NOT EXISTS idx_transactions_bill_id ON public.transactions (bill_id);
CREATE INDEX IF NOT EXISTS idx_transactions_stall_period ON public.transactions (stall_id, period_year);

-- Status transaksi lama bercampur: mobile menulis 'paid', UI web memakai 'LUNAS'.
CREATE OR REPLACE FUNCTION public.is_paid_transaction_status(value text)
RETURNS boolean
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT upper(coalesce(value, '')) IN ('PAID', 'LUNAS');
$$;

-- ---------------------------------------------------------------------------
-- 4) Saldo tagihan (dihitung dari transaksi, tidak disimpan)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE VIEW public.retribution_bill_balances
WITH (security_invoker = true) AS
SELECT
  b.id,
  b.market_id,
  b.stall_id,
  b.types_id,
  b.period_year,
  b.amount_due,
  b.due_date,
  b.note,
  coalesce(p.paid, 0)::numeric(15,2) AS amount_paid,
  (b.amount_due - coalesce(p.paid, 0))::numeric(15,2) AS outstanding,
  CASE
    WHEN b.status = 'DIBATALKAN' THEN 'DIBATALKAN'
    WHEN coalesce(p.paid, 0) >= b.amount_due THEN 'LUNAS'
    WHEN coalesce(p.paid, 0) > 0 THEN 'CICILAN'
    ELSE 'BELUM_LUNAS'
  END AS status,
  (b.status = 'AKTIF' AND coalesce(p.paid, 0) < b.amount_due) AS is_open
FROM public.retribution_bills b
LEFT JOIN (
  SELECT t.bill_id, sum(t.amount) AS paid
  FROM public.transactions t
  WHERE t.bill_id IS NOT NULL
    AND public.is_paid_transaction_status(t.status)
  GROUP BY t.bill_id
) p ON p.bill_id = b.id;

-- ---------------------------------------------------------------------------
-- 5) Terbitkan tagihan tahunan dari retribution_rates
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.generate_retribution_bills(
  p_market_id bigint,
  p_year integer,
  p_types_id bigint DEFAULT NULL,
  p_due_date date DEFAULT NULL
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  inserted integer;
BEGIN
  IF NOT (public.is_current_user_admin_full() OR public.is_current_user_market_member(p_market_id)) THEN
    RAISE EXCEPTION 'Tidak berwenang menerbitkan tagihan pasar ini';
  END IF;

  IF p_year IS NULL OR p_year < 2000 OR p_year > 2100 THEN
    RAISE EXCEPTION 'Tahun tagihan tidak valid';
  END IF;

  INSERT INTO public.retribution_bills (market_id, stall_id, types_id, period_year, amount_due, due_date)
  SELECT r.market_id, r.stall_id, r.types_id, p_year, r.amount,
         coalesce(p_due_date, make_date(p_year, 3, 31))
  FROM public.retribution_rates r
  JOIN public.stalls s ON s.id = r.stall_id
  JOIN public.retribution_types t ON t.id = r.types_id
  WHERE r.market_id = p_market_id
    AND r.stall_id IS NOT NULL
    AND r.amount > 0
    AND s.status = 'AKTIF'
    AND t.billing_period = 'TAHUNAN'
    AND (p_types_id IS NULL OR r.types_id = p_types_id)
  ON CONFLICT (stall_id, types_id, period_year) DO NOTHING;

  GET DIAGNOSTICS inserted = ROW_COUNT;
  RETURN inserted;
END;
$$;

REVOKE ALL ON FUNCTION public.generate_retribution_bills(bigint, integer, bigint, date) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.generate_retribution_bills(bigint, integer, bigint, date) TO authenticated;

-- ---------------------------------------------------------------------------
-- 5b) Bayar tagihan lapak secara FIFO (tunggakan terlama dilunasi lebih dulu)
--     Satu pembayaran boleh menutup beberapa tahun sekaligus; bila uang lebih
--     dari total tunggakan seluruh baris dibatalkan (exception).
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.pay_retribution_bills(
  p_stall_id bigint,
  p_amount numeric,
  p_types_id bigint DEFAULT NULL,
  p_payment_method text DEFAULT 'Tunai',
  p_payer_name text DEFAULT NULL,
  p_note text DEFAULT NULL
)
RETURNS TABLE (bill_id bigint, period_year integer, amount numeric)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  bill record;
  remaining numeric;
  applied numeric;
  stall_market bigint;
  bill_rate_id bigint;
BEGIN
  IF p_amount IS NULL OR p_amount <= 0 THEN
    RAISE EXCEPTION 'Jumlah pembayaran harus lebih dari 0';
  END IF;

  SELECT s.market_id INTO stall_market FROM public.stalls s WHERE s.id = p_stall_id;
  IF stall_market IS NULL THEN
    RAISE EXCEPTION 'Lapak % tidak ditemukan', p_stall_id;
  END IF;

  IF NOT (public.is_current_user_admin_full() OR public.is_current_user_market_member(stall_market)) THEN
    RAISE EXCEPTION 'Tidak berwenang membayar tagihan pasar ini';
  END IF;

  remaining := p_amount;

  FOR bill IN
    SELECT b.id, b.market_id, b.stall_id, b.types_id, b.period_year,
           b.amount_due - coalesce((
             SELECT sum(t.amount) FROM public.transactions t
             WHERE t.bill_id = b.id AND public.is_paid_transaction_status(t.status)
           ), 0) AS outstanding
    FROM public.retribution_bills b
    WHERE b.stall_id = p_stall_id
      AND b.status = 'AKTIF'
      AND (p_types_id IS NULL OR b.types_id = p_types_id)
      AND b.amount_due > coalesce((
        SELECT sum(t.amount) FROM public.transactions t
        WHERE t.bill_id = b.id AND public.is_paid_transaction_status(t.status)
      ), 0)
    ORDER BY b.period_year ASC, b.id ASC
  LOOP
    EXIT WHEN remaining <= 0;

    applied := least(remaining, bill.outstanding);
    IF applied <= 0 THEN
      CONTINUE;
    END IF;

    SELECT r.id INTO bill_rate_id
    FROM public.retribution_rates r
    WHERE r.stall_id = bill.stall_id AND r.types_id = bill.types_id
    ORDER BY r.id DESC
    LIMIT 1;

    INSERT INTO public.transactions (
      market_id, stall_id, rate_id, bill_id, period_year, amount,
      payment_method, payer_name, status, source, sync_status, note
    ) VALUES (
      bill.market_id, bill.stall_id, bill_rate_id, bill.id, bill.period_year, applied,
      coalesce(p_payment_method, 'Tunai'), p_payer_name, 'paid', 'TAGIHAN', 'SYNCED', p_note
    );

    remaining := remaining - applied;

    bill_id := bill.id;
    period_year := bill.period_year;
    amount := applied;
    RETURN NEXT;
  END LOOP;

  IF remaining > 0 THEN
    RAISE EXCEPTION 'Pembayaran melebihi total tunggakan (lebih %)', remaining;
  END IF;
END;
$$;

REVOKE ALL ON FUNCTION public.pay_retribution_bills(bigint, numeric, bigint, text, text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.pay_retribution_bills(bigint, numeric, bigint, text, text, text) TO authenticated;

-- ---------------------------------------------------------------------------
-- 6) Penjaga transaksi bertagihan
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.guard_transaction_bill()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  bill record;
  paid numeric;
BEGIN
  IF NEW.bill_id IS NULL THEN
    RETURN NEW;
  END IF;

  SELECT * INTO bill FROM public.retribution_bills WHERE id = NEW.bill_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Tagihan % tidak ditemukan', NEW.bill_id;
  END IF;
  IF bill.status <> 'AKTIF' THEN
    RAISE EXCEPTION 'Tagihan % sudah dibatalkan', NEW.bill_id;
  END IF;

  IF NEW.stall_id IS NULL THEN
    NEW.stall_id := bill.stall_id;
  ELSIF NEW.stall_id <> bill.stall_id THEN
    RAISE EXCEPTION 'Transaksi tidak sesuai lapak tagihan';
  END IF;

  IF NEW.market_id IS NULL THEN
    NEW.market_id := bill.market_id;
  ELSIF NEW.market_id <> bill.market_id THEN
    RAISE EXCEPTION 'Transaksi tidak sesuai pasar tagihan';
  END IF;

  NEW.period_year := bill.period_year;

  IF public.is_paid_transaction_status(NEW.status) THEN
    SELECT coalesce(sum(t.amount), 0) INTO paid
    FROM public.transactions t
    WHERE t.bill_id = NEW.bill_id
      AND public.is_paid_transaction_status(t.status)
      AND t.id IS DISTINCT FROM NEW.id;

    IF paid + NEW.amount > bill.amount_due THEN
      RAISE EXCEPTION 'Pembayaran melebihi sisa tagihan (sisa %)', bill.amount_due - paid;
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_guard_transaction_bill ON public.transactions;
CREATE TRIGGER trg_guard_transaction_bill
BEFORE INSERT OR UPDATE ON public.transactions
FOR EACH ROW
EXECUTE FUNCTION public.guard_transaction_bill();

CREATE OR REPLACE FUNCTION public.touch_retribution_bill()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_touch_retribution_bill ON public.retribution_bills;
CREATE TRIGGER trg_touch_retribution_bill
BEFORE UPDATE ON public.retribution_bills
FOR EACH ROW
EXECUTE FUNCTION public.touch_retribution_bill();

-- ---------------------------------------------------------------------------
-- 7) RLS
-- ---------------------------------------------------------------------------
ALTER TABLE public.retribution_bills ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "retribution_bills_select" ON public.retribution_bills;
DROP POLICY IF EXISTS "retribution_bills_insert" ON public.retribution_bills;
DROP POLICY IF EXISTS "retribution_bills_update" ON public.retribution_bills;
DROP POLICY IF EXISTS "retribution_bills_delete" ON public.retribution_bills;

CREATE POLICY "retribution_bills_select"
ON public.retribution_bills FOR SELECT TO authenticated
USING (true);

CREATE POLICY "retribution_bills_insert"
ON public.retribution_bills FOR INSERT TO authenticated
WITH CHECK (
  public.is_current_user_admin_full()
  OR public.is_current_user_market_member(market_id)
);

CREATE POLICY "retribution_bills_update"
ON public.retribution_bills FOR UPDATE TO authenticated
USING (
  public.is_current_user_admin_full()
  OR public.is_current_user_market_member(market_id)
)
WITH CHECK (
  public.is_current_user_admin_full()
  OR public.is_current_user_market_member(market_id)
);

CREATE POLICY "retribution_bills_delete"
ON public.retribution_bills FOR DELETE TO authenticated
USING (
  public.is_current_user_admin_full()
  OR public.is_current_user_market_member(market_id)
);

-- ---------------------------------------------------------------------------
-- 8) Jenis Jaspro tahunan (tanpa tarif; tarif per lapak diisi admin)
--    Harga Jaspro berbeda tiap lapak -> isi lewat dialog Tarif di halaman
--    Lapak atau impor CSV tarif. Lewati blok ini bila belum diperlukan.
-- ---------------------------------------------------------------------------
INSERT INTO public.retribution_types (code, name, category, unit, billing_period, allow_installment, notes, market_id)
SELECT 'NGD-JASPRO', 'Jaspro', 'Retribusi Pedagang', 'TAHUN', 'TAHUNAN', true,
       'Jasa profesi tahunan, dapat dicicil; tarif per lapak', 39
WHERE EXISTS (SELECT 1 FROM public.markets WHERE id = 39)
  AND NOT EXISTS (SELECT 1 FROM public.retribution_types WHERE code = 'NGD-JASPRO');

COMMIT;

